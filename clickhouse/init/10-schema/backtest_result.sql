CREATE TABLE IF NOT EXISTS dc.backtest_result
(
    `run_time` DateTime,
    `sid` String,
    `strategy_name` String,
    `symbol` String,
    `text` String,
    `begin_date` String,
    `end_date` String,
    `trade_count` Int32,
    `win_count` Int32,
    `loss_count` Int32,
    `flat_count` Int32,
    `win_rate` Float64,
    `total_return_pct` Float64,
    `profit_factor` Float64 DEFAULT 0,
    `max_drawdown_pct` Float64,
    `initial_capital` Float64,
    `final_capital` Float64,
    `total_pnl` Float64,
    `report_path` String,
    `payload` String,
    `strategy_version` String DEFAULT '',
    `baseline_version` Nullable(String) DEFAULT NULL,
    `runtime_type` LowCardinality(String) DEFAULT 'LEGACY_SPRING',
    `scene` String DEFAULT '',
    `fit_payload` String DEFAULT '',
    `forward_score` Float64 DEFAULT 0,
    `slice_count` Int32 DEFAULT 0,
