    `best_rank` Int32,
    `symbol_count` Int32,
    `fit_window_days` Int32,
    `validate_window_days` Int32,
    `forward_window_days` Int32,
    `min_slice_count` Int32,
    `optimization_objective` String,
    `min_forward_contribution` Float64,
