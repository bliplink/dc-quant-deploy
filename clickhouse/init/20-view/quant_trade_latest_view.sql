CREATE VIEW IF NOT EXISTS dc.quant_trade_latest_view
(
    `quantID` String,
    `venueTypeGW` String,
    `securityID` String,
    `orderID` String,
    `execID` String,
    `tradeDate` Date32,
    `location` String,
    `demo` String,
    `marketIndicator` String,
    `clOrdID` String,
    `eventTime` String,
    `side` String,
    `lastPx` Nullable(Decimal(38, 12)),
    `lastQty` Nullable(Decimal(38, 12)),
    `createTime` String,
    `updateTime` UInt64,
    `source` String,
    `userID` String,
    `userName` String,
    `algoName` String,
    `strategyName` String,
    `strategyVersion` String,
    `scene` String,
    `strategyPayload` String,
    `venues` String,
    `symbol` String,
    `ordType` String,
    `execType` String,
    `positionSide` String,
    `orderQty` Nullable(Decimal(38, 12)),
    `cumQty` Nullable(Decimal(38, 12)),
    `price` Nullable(Decimal(38, 12)),
    `avgPx` Nullable(Decimal(38, 12)),
    `fee` Nullable(Decimal(38, 12)),
    `realizedPnl` Nullable(Decimal(38, 12)),
    `info1` String,
    `info2` String,
    `info3` String,
    `info4` String,
    `info5` String
)
AS SELECT
    quantID,
    venueTypeGW,
    securityID,
    orderID,
    execID,
    argMax(tradeDate, versionTime) AS tradeDate,
    argMax(location, versionTime) AS location,
    demo,
    argMax(marketIndicator, versionTime) AS marketIndicator,
    argMax(clOrdID, versionTime) AS clOrdID,
    argMax(eventTime, versionTime) AS eventTime,
    argMax(side, versionTime) AS side,
    argMax(lastPx, versionTime) AS lastPx,
    argMax(lastQty, versionTime) AS lastQty,
    argMax(createTime, versionTime) AS createTime,
    max(versionTime) AS updateTime,
    argMax(source, versionTime) AS source,
    argMax(userID, versionTime) AS userID,
    argMax(userName, versionTime) AS userName,
    argMax(algoName, versionTime) AS algoName,
    argMax(strategyName, versionTime) AS strategyName,
    argMax(strategyVersion, versionTime) AS strategyVersion,
    argMax(scene, versionTime) AS scene,
    argMax(strategyPayload, versionTime) AS strategyPayload,
    argMax(venues, versionTime) AS venues,
    argMax(symbol, versionTime) AS symbol,
    argMax(ordType, versionTime) AS ordType,
    argMax(execType, versionTime) AS execType,
    argMax(positionSide, versionTime) AS positionSide,
    argMax(orderQty, versionTime) AS orderQty,
    argMax(cumQty, versionTime) AS cumQty,
    argMax(price, versionTime) AS price,
    argMax(avgPx, versionTime) AS avgPx,
    argMax(fee, versionTime) AS fee,
    argMax(realizedPnl, versionTime) AS realizedPnl,
    argMax(info1, versionTime) AS info1,
    argMax(info2, versionTime) AS info2,
    argMax(info3, versionTime) AS info3,
    argMax(info4, versionTime) AS info4,
    argMax(info5, versionTime) AS info5
FROM
(
    SELECT
        *,
        updateTime AS versionTime
    FROM dc.quant_trade
)
GROUP BY
    quantID,
    venueTypeGW,
    securityID,
    orderID,
    execID,
    demo;
